const assert = require('assert');
const fs = require('fs');
const path = require('path');
const styles = fs.readFileSync(path.join(__dirname, '../../components/button/button.wxss'), 'utf8');
assert.match(styles, /\.btn--secondary \{[^}]*border: 3rpx solid #002900;/, '全局 secondary 仍保留深墨描边');
assert.match(styles, /\.btn--secondary-soft \{[^}]*border: 3rpx solid rgba\(0, 41, 0, 0\.24\);/, '信件 CTA 使用浅色半透明描边');
const roomTemplate = fs.readFileSync(path.join(__dirname, '../../pages/life-scene/life-scene.wxml'), 'utf8');
assert.equal(/variant="secondary-soft"/.test(roomTemplate) && /variant="secondary"/.test(roomTemplate), true, '小游戏邀请用实线 secondary，外出收信与收下仍用 secondary-soft');
let component;
const previous = global.Component;
global.Component = value => { component = value; };
require('../../components/button/button');
global.Component = previous;
assert.equal(component.properties.size.value, 'default', '原有按钮不指定尺寸时保持默认');
assert.equal(component.properties.iconText.value, '', '原有按钮不指定emoji时不显示文字图标');
assert.equal(component.properties.icon.value, '', '现有按钮不传图标时仍只有文字');
const events = [];
const page = { data: { disabled: false, icon: '' }, triggerEvent: name => events.push(name) };
component.methods.onTap.call(page);
page.data.icon = '/assets/ui/3d-actions/runtime/ui_3d_listen_speech_bubbles_128_v01.png';
component.methods.onTap.call(page);
page.data.iconText = '✅'; page.data.size = 'small';
component.methods.onTap.call(page);
assert.deepEqual(events, ['tap', 'tap', 'tap'], '有无图标、emoji完成态都只触发一次点击事件');
page.data.disabled = true;
component.methods.onTap.call(page);
assert.equal(events.length, 3, '禁用状态不触发点击');
console.log('共享按钮检查通过：图标可选、有无图标点击一致、禁用不触发。');
