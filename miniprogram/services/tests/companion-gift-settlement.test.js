const assert = require('assert');
const stars = require('../iaa-star-unlock-adapter');
const originalNow = Date.now;
let now = Date.parse('2026-10-04T23:59:59.999+08:00');
Date.now = () => now;
const day = () => stars.getRoomStarView().then(result => result.data);
const photo = { image: 'fixture-photo.webp', title: '窗边茶会', line: '一起在窗边喝了一杯茶。' };
(async () => {
  stars.configureRoom('gift-settlement');
  await stars.recordLetterOpen(await day());
  const start = await stars.recordDrawingStart(await day());
  const first = await stars.recordDrawingComplete(start.data, 'first-work');
  assert.equal(first.giftStars, 10, '道具临摹达标每次 +10');
  assert.equal(first.awardedStars, 10);
  assert.equal(first.data.star.balance, 23, '初始2星，开信基础11、画好 +10，进入画纸不发星');
  assert.equal(first.data.star.companionDays, 1, '完成活动记一天');
  const repeated = await stars.recordDrawingComplete(start.data, 'first-work');
  assert.equal(repeated.awardedStars, 0);
  assert.equal((await stars.recordDrawingComplete(first.data, 'second-work')).awardedStars, 10, '同日第二幅仍 +10');
  now += 1;
  assert.equal((await stars.recordDrawingComplete(await day(), 'first-work')).awardedStars, 0, '跨午夜旧回调不占用新日');
  await stars.recordLetterOpen(await day());
  const nextDay = await stars.recordDrawingComplete(await day(), 'next-day-work');
  assert.equal(nextDay.giftStars, 10);
  assert.equal(nextDay.baseAwardedStars, 0);
  assert.equal(nextDay.drawingGift.kind, 'prop');

  stars.configureRoom('invalid-work');
  assert.equal((await stars.recordDrawingComplete(await day(), '')).ok, false);
  assert.equal((await day()).star.balance, 2);
  await stars.recordLetterOpen(await day());
  assert.equal((await stars.recordDrawingComplete(await day(), 'valid-after-error')).giftStars, 10);

  stars.configureRoom('tea-effective');
  stars.beginTeaActivity({ id: 'free-tea', photo });
  assert.equal((await day()).star.companionDays, 0, '进入不计日');
  stars.chooseTea('plain');
  assert.equal((await day()).star.companionDays, 0, '选茶不计日');
  const completed = stars.confirmTeaActivity();
  assert.equal(completed.effectiveAdded, false, '茶会永不加天');
  let view = await day();
  assert.equal(view.star.balance, 2, '免费茶会不发星');
  assert.equal(view.star.baseClaimed, false, '不领取基础奖励');
  assert.equal(view.star.companionDays, 0, '茶会完成不加天');
  assert.equal(stars.confirmTeaActivity().duplicate, true);
  const completionDate = completed.data.current.completedDate;
  now += 86400000;
  stars.confirmTeaActivity();
  assert.equal((await day()).star.companionDays, 0, '次日查看结果不补计一天');
  const collected = stars.collectTeaActivity();
  assert.equal(collected.memory.date, completionDate, '稍后收下保留完成日期');
  assert.equal((await day()).star.companionDays, 0);
  await stars.recordLetterOpen(await day());
  view = (await stars.recordDrawingStart(await day())).data;
  await stars.recordDrawingComplete(view, 'fund-tea');
  assert.equal((await day()).star.companionDays, 1, '完成画画才记天');
  now += 86400000;
  await stars.recordLetterOpen(await day());
  await stars.recordCompanion(await day());
  const funded = (await day()).star.balance;
  stars.beginTeaActivity({ id: 'paid-tea', photo });
  stars.chooseTea('flower');
  assert.equal(stars.confirmTeaActivity().effectiveAdded, false, '茶会永不加天');
  assert.equal((await day()).star.balance, funded - 20);
  assert.equal((await day()).star.companionDays, 2, '同日茶会不重复加天');
  stars.collectTeaActivity();
  now += 86400000;
  await stars.recordLetterOpen(await day());
  await stars.recordDrawingComplete(await day(), 'fund-next-day');
  now += 86400000;
  await stars.recordLetterOpen(await day());
  await stars.recordDrawingComplete(await day(), 'fund-final-day');
  const beforePaid = await day();
  stars.beginTeaActivity({ id: 'paid-next-day', photo });
  stars.chooseTea('plain');
  assert.equal(stars.confirmTeaActivity().effectiveAdded, false, '付费茶会也不加天');
  const afterPaid = await day();
  assert.equal(afterPaid.star.companionDays, beforePaid.star.companionDays, '茶会不改变天数');
  assert.equal(afterPaid.star.balance, beforePaid.star.balance - 20);
  console.log('道具临摹 +10/重复进入/跨日去重，以及茶会不加天/不发星/恢复通过。');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { Date.now = originalNow; });
