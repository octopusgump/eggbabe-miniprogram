const assert = require('assert');
const data = new Map();
global.wx = { getStorageSync: key => data.get(key), setStorageSync: (key, value) => data.set(key, structuredClone(value)) };
const location = require.resolve('../companion-letter-progress');
let progress = require(location);
const date = '2026-10-19';
assert.equal(progress.read('owner-a_pet-a', 'listen', date).entered, false);
assert.equal(progress.markExpanded('owner-a_pet-a', 'listen', false, date).ok, false, '未进入不能展开');
progress.markEntered('owner-a_pet-a', 'listen', date);
assert.equal(progress.read('owner-a_pet-a', 'listen', date).entered, true);
assert.equal(progress.read('owner-a_pet-a', 'listen', date).tomorrow, false);
assert.equal(progress.read('owner-a_pet-a', 'drawing', date).entered, false, '活动之间隔离');
assert.equal(progress.read('owner-b_pet-a', 'listen', date).entered, false, '用户之间隔离');
assert.equal(progress.read('owner-a_pet-b', 'listen', date).entered, false, '宠物之间隔离');
progress.markExpanded('owner-a_pet-a', 'listen', false, date);
assert.equal(progress.read('owner-a_pet-a', 'listen', date).tomorrow, true);
delete require.cache[location]; progress = require(location);
assert.equal(progress.read('owner-a_pet-a', 'listen', date).tomorrow, true, '重载可从本机恢复');
assert.equal(progress.read('owner-a_pet-a', 'listen', '2026-10-20').entered, false, '次日状态重置');
assert.equal(progress.markExpanded('legacy-completed', 'listen', true, date).ok, true, '旧的已完成活动可直接展开');
global.wx.setStorageSync = () => { throw Error('local storage unavailable'); };
assert.equal(progress.markEntered('write-failed', 'drawing', date).ok, false);
assert.equal(progress.read('write-failed', 'drawing', date).entered, true, '保存失败时当前运行仍保留进入状态');
console.log('小游戏信件进度通过：进入与展开分开、用户宠物活动隔离、重载恢复、跨日重置、已完成兼容、写失败保留当前运行。');
