// 微信小程序 require 不能直接载入 JSON；保留 JSON 为源，生成同内容的 JS。
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../miniprogram/fixtures');
const bank = JSON.parse(fs.readFileSync(path.join(root, 'listen-bank.json'), 'utf8'));
const generated = '// Generated by scripts/generate-listen-bank.js; edit listen-bank.json instead.\nmodule.exports = ' + JSON.stringify(bank, null, 2) + ';\n';
const target = path.join(root, 'listen-bank.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) { console.error('听你说运行题库与 JSON 不一致'); process.exit(1); }
  console.log('听你说 JSON 与小程序 JS 题库一致。');
} else fs.writeFileSync(target, generated);
